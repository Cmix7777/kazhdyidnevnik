    fun isMockDay(date: LocalDate): Boolean {
        if (date.dayOfWeek != DayOfWeek.SUNDAY || date.isBefore(firstDay)) return false
        return if (!date.isAfter(switchDay)) {
            daysBetween(firstDay, date) % 21 == 0L
        } else {
            daysBetween(switchDay, date) % 14 == 0L
        }
    }

    /** Порядковый номер пробника (0 — первый). */
    fun index(date: LocalDate): Int =
        if (!date.isAfter(switchDay)) {
            (daysBetween(firstDay, date) / 21).toInt()
        } else {
            (daysBetween(firstDay, switchDay) / 21).toInt() + (daysBetween(switchDay, date) / 14).toInt()
        }

    fun taskFor(date: LocalDate): MockTask = tasks[index(date).coerceAtLeast(0) % tasks.size]

    fun fullText(task: MockTask): String = task.text + "\n" + COMMON

    /** Ближайший пробник начиная с даты (включительно). */
    fun next(from: LocalDate): LocalDate? {
        var date = from
        repeat(400) {
            if (isMockDay(date)) return date
            date = date.plusDays(1)
        }
        return null
    }
